// Encodes text lines (as produced by DecodeTokenized) into a tokenized program
// including the 0xFF envelope and the trailing 0x1A.
inline std::string EncodeTokenized(const std::vector<DecodedLine>& lines) {
  std::string records;
  for (const DecodedLine& line : lines) {
    const std::string text = detail::EncodeLineText(line.source);
    // The offset recorded is the start of the following line record, relative
    // to the file start (the envelope byte is at 0).
    const unsigned offset = static_cast<unsigned>(1 + records.size() + 2 + 2 + text.size() + 1);
    records += static_cast<char>(offset & 0xFF);
    records += static_cast<char>((offset >> 8) & 0xFF);
    records += static_cast<char>(line.number & 0xFF);
    records += static_cast<char>((line.number >> 8) & 0xFF);
    records += text;
    records += static_cast<char>(0x00);
  }
  std::string out;
  out += static_cast<char>(0xFF);
  out += records;
  out += static_cast<char>(0x00);
  out += static_cast<char>(0x00);
  out += static_cast<char>(0x1A);
  return out;
}

